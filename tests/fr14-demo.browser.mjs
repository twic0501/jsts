// Availability demo: real FR12/public search, protected FR14 blocked until authoritative Document/mapping exist.
import { chromium, expect } from '@playwright/test'
import fs from 'node:fs/promises'
import { randomBytes, randomUUID } from 'node:crypto'
const state=JSON.parse(await fs.readFile('.local/fr14-demo/state.json','utf8'))
if(state.status!=='running')throw new Error('Start node scripts/fr14/demo.mjs first.')
if(state.origin!=='https://localhost:5443'||!/^fr14_demo_[0-9a-f]+$/.test(state.dbName))throw new Error('Only the disposable local demo is allowed.')
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_BROWSER_PATH||'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true,args:['--enable-unsafe-swiftshader']})
try {
  const context=await browser.newContext({ignoreHTTPSErrors:true,viewport:{width:1440,height:960},reducedMotion:'reduce'})
  const page=await context.newPage(),errors=[]
  page.on('pageerror',error=>errors.push(error.message))
  await page.goto(state.origin)
  await expect(page.getByRole('button',{name:'Đăng nhập',exact:true})).toBeEnabled()
  await expect(page.locator('.pm-auth-dialog')).toHaveCount(0)
  // No public corpus/search fixtures: exercise the seeded legacy Paper corpus and actual model/API.
  const search=await context.request.post(state.origin+'/api/v1/search',{data:{query:'machine',topK:5},timeout:60000})
  expect(search.status()).toBe(200)
  expect((await search.json()).items.length).toBeGreaterThan(0)
  await page.getByRole('searchbox',{name:'Tìm bài báo'}).fill('machine')
  await page.getByRole('button',{name:'Tìm trong sách',exact:true}).click()
  const library=page.getByRole('button',{name:'Thư viện bài báo',exact:true});if(await library.getAttribute('aria-expanded')!=='true')await library.click()
  await page.locator('.paper-select').first().click()
  await page.evaluate(()=>{window.demoCanvas=document.querySelector('[data-testid="magic-book"]');if(!window.demoCanvas)throw new Error('Scene missing');window.demoCast=window.demoCanvas.dataset.castId})
  await page.getByRole('button',{name:'Lưu bài báo',exact:true}).click()
  let dialog=page.locator('.pm-auth-dialog')
  await dialog.getByRole('button',{name:'Đăng ký',exact:true}).click()
  const email='qa-'+randomUUID()+'@example.test',password=randomBytes(24).toString('hex')
  await dialog.getByLabel('Email',{exact:true}).fill(email)
  await dialog.getByLabel('Tên hiển thị',{exact:true}).fill('Local Demo QA')
  await dialog.getByLabel('Mật khẩu',{exact:true}).fill(password)
  await dialog.getByLabel('Xác nhận mật khẩu',{exact:true}).fill(password)
  await dialog.getByRole('button',{name:'Tạo tài khoản',exact:true}).click()
  await expect(page.locator('.pm-auth-dialog')).toHaveCount(0)
  await page.getByRole('button',{name:'Lưu bài báo',exact:true}).click()
  dialog=page.locator('.pm-auth-dialog')
  await dialog.getByLabel('Email',{exact:true}).fill(email)
  await dialog.getByLabel('Mật khẩu',{exact:true}).fill(password)
  await dialog.getByRole('button',{name:'Đăng nhập',exact:true}).click()
  await expect(page.getByRole('button',{name:'Đăng xuất',exact:true})).toBeVisible()
  await expect(page.getByRole('button',{name:'Lưu bài báo',exact:true})).toHaveAttribute('aria-pressed','false')
  await expect(page.locator('.toast')).toContainText('Document Service')
  expect(await page.evaluate(()=>window.demoCanvas===document.querySelector('[data-testid="magic-book"]')&&window.demoCast===window.demoCanvas.dataset.castId)).toBe(true)
  await expect(page.getByRole('searchbox',{name:'Tìm bài báo'})).toHaveValue('machine')
  const session=await(await context.request.get(state.origin+'/api/v4/sessions/current')).json()
  expect(session.user.email).toBe(email)
  const cookie=(await context.cookies()).find(c=>c.name==='__Host-pm_session')
  expect(Boolean(cookie?.httpOnly&&cookie?.secure)).toBe(true)
  const profile=await context.request.get(state.origin+'/api/v4/users/me');expect(profile.status()).toBe(200)
  const updated=await context.request.patch(state.origin+'/api/v4/users/me',{headers:{Origin:state.origin,'X-CSRF-Token':session.csrfToken,'Idempotency-Key':randomUUID(),'If-Match':profile.headers().etag},data:{displayName:'Local Demo Verified'}})
  expect(updated.status()).toBe(200)
  for(const method of ['GET','PUT','DELETE']){
    const path='/api/v4/users/me/bookmarks'+(method==='GET'?'':'/'+randomUUID())
    const result=await context.request.fetch(state.origin+path,{method,headers:{Origin:state.origin,'X-CSRF-Token':session.csrfToken,'Idempotency-Key':randomUUID(),...(method==='PUT'?{'If-None-Match':'*'}:method==='DELETE'?{'If-Match':'"1"'}:{})},...(method==='PUT'?{data:{saved:true}}:{})})
    const body=await result.json()
    expect(result.status(),`${method}: ${body.error?.code}`).toBe(503);expect(body.error.code).toBe('BOOKMARK_DEPENDENCY_UNAVAILABLE')
  }
  await page.reload();await expect(page.getByRole('button',{name:'Đăng xuất',exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Bài đã lưu 0 bài'}).click()
  await expect(page.locator('.saved-local-note')).toContainText('Bookmark tài khoản chưa sẵn sàng')
  await page.getByRole('button',{name:'Đăng xuất',exact:true}).click()
  await expect(page.getByRole('button',{name:'Đăng nhập',exact:true})).toBeEnabled()
  expect((await context.request.get(state.origin+'/api/v4/users/me')).status()).toBe(401)
  expect((await context.request.get(state.origin+'/api/v4/users/me/bookmarks')).status()).toBe(401)
  expect(errors).toEqual([])
  console.log('PASS live disposable demo: real public search + six FR12 APIs, secure cookie/reload/logout and unchanged auth scene; all three FR14 APIs truthfully fail closed (Document/mapping missing).')
}finally{await browser.close()}
